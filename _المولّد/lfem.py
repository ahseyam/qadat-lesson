def _imp(m):
    """اعرض ← اعرضي · اعرضه ← اعرضيه — والضمير يبقى على مرجعه."""
    return m.group(1) + IMP[m.group(2)] + (m.group(3) or "")


def _v(m):
    core = m.group(2)
    return m.group(1) + "ت" + core[1:] + m.group(0)[len(m.group(1)) + len(core):]


def lfem(text: str) -> str:
    if not text:
        return text
    text = _RX_PH.sub(lambda m: PH[m.group(0)], text)
    text = _RX_I.sub(_imp, text)
    for i, k in enumerate(KEEP):                 # عزل المحميّ بعلامةٍ لا تمسّها الأفعال
        text = text.replace(k, f"\x00{i}\x00")
    text = _RX_V.sub(_v, text)
    text = _RX_W.sub(lambda m: W[m.group(1)], text)
    for i, k in enumerate(KEEP):
        text = text.replace(f"\x00{i}\x00", k)
    return text


def walk(obj):
    """تأنيث كل نصٍّ داخل بنية الدرس (قوائم وقواميس متداخلة) — المفاتيح والقيم."""
    if isinstance(obj, str):
        return lfem(obj)
    if isinstance(obj, dict):
        return {walk(k): walk(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [walk(v) for v in obj]
    if isinstance(obj, tuple):
        return tuple(walk(v) for v in obj)
    return obj
